#!/usr/bin/env python
"""Generate the seed-ablation configs: one replicate, several seeds, plus a driver script.

The bootstrap ensembles vary the training replicate and hold the seed fixed, which measures
the finite-sample component of model uncertainty and nothing else. finetune.py seeds every
run identically (``set_global_seed`` offsets a config ``seed`` by 42, default 0), so all ten
672hr_stable members share one initialization and one training-sample order. That is a clean
bootstrap, but it means member spread omits the optimization-path component entirely -- a
second, independent reason the ensemble spread understates error, alongside the overfitting
documented in NOTES.

This script generates the complementary axis: the SAME replicate trained under different
seeds, so the two variance components can be compared directly instead of assumed.

Exactly two things differ between arms:

    seed                torch/numpy/random seed (42+seed) and the train sampler's seed
    path_experiment     where checkpoints land

plus job_id so the wandb runs are distinguishable. Everything else is inherited verbatim from
--base-config, which defaults to 672hr_stable member boot01 -- not config.yaml -- precisely so
"identical in every other respect" is guaranteed by construction rather than by re-deriving a
long list of fields and hoping they match.

WHY SEED 0 NEED NOT BE RE-RUN: seed 0 reproduces pre-existing behaviour bit for bit
(``set_global_seed(0)`` is ``manual_seed(42)``, and the sampler's default seed is already 0),
so 672hr_stable/boot01 IS the seed-0 arm. Its config is still generated, for anyone who wants
to verify that claim, but the driver script skips it by default. Use --include-seed-0 to get a
runner that trains it anyway.

WHY THE SEED HAS TO REACH THE SAMPLER: DistributedSampler shuffles from a private
torch.Generator seeded with ``seed + epoch``, not from the global RNG. Varying only the global
seed changes LoRA's lora_A init and the dropout masks but leaves the training order byte
identical, which would understate the very component this ablation exists to measure.
finetune.py's get_dataloaders passes ``seed`` to the train sampler for this reason. The
validation sampler is deliberately left at its default: the loop scores a fixed
iters_per_epoch_valid prefix, so reseeding it would change which frames are scored and break
comparability with every existing member.

NAMING: the arms are `672hr_stable_seed`, after the parent regime they reseed. Everything --
the config directory, the checkpoint root under ar_seg_bootstrap/, the job_id prefix and
run_bootstrap_inference's regime key -- uses that name, so the regime naming convention
resolves all three roots with no explicit flags.

ONE PROVENANCE WRINKLE from that rename (2026-10-30): the three arms that ACTUALLY TRAINED did
so before it, under the old `seed_ablation` / `AR-seg_seedabl` names, so their wandb runs log
job_id `AR-seg_seedabl_seed{00,01,02}` while a fresh run of this script emits
`AR-seg_672hr_stable_seed_seed{00,01,02}`. The checkpoints and results are unaffected -- job_id
is a label -- but do not expect a regenerated config to match the completed runs byte for byte
on that one key. The runs are bm06c9dt (seed01), x7m7u8fz (seed02) and j6huxcrn (seed00, which
is 672hr_stable/boot01); see NOTES.

Usage:
    python make_seed_ablation_configs.py                  # seeds 0,1,2
    python make_seed_ablation_configs.py --seeds 0 1 2 3  # a wider sweep
    python make_seed_ablation_configs.py --include-seed-0 # runner trains seed 0 too
"""

import argparse
import copy
import os
import stat

import yaml

HEADER = """\
# GENERATED by make_seed_ablation_configs.py -- do not edit by hand.
#
# Seed-ablation arm {n} of {total}: seed {seed}.
#   training index : {train}
#   checkpoints    : {experiment}
#   derived from   : {base}
#
# Every arm trains the SAME replicate. The only differences from the base config are `seed`,
# `job_id` and `path_experiment`, so the spread across arms is the optimization-path component
# of model uncertainty -- initialization and training-sample order -- with the finite-sample
# component held fixed. Compare it against the across-replicate spread of the {ensemble}
# ensemble, which measures the finite-sample component with the seed held fixed.
#
# Regenerate with: python make_seed_ablation_configs.py
"""

SEED_0_NOTE = """\
#
# NOTE: seed 0 is a bit-for-bit reproduction of the base config -- set_global_seed(0) is
# manual_seed(42) and the sampler's default seed is already 0 -- so this arm has ALREADY been
# trained, as {base_experiment}. Running this config would spend the full
# wall time reproducing checkpoints that already exist. The driver script skips it; point the
# analysis at the existing directory instead.
"""

RUNNER = """\
#!/usr/bin/env bash
# GENERATED by make_seed_ablation_configs.py -- runs the seed ablation sequentially.
#
# One replicate ({train}), {n_run} seeds. Each arm is an
# independent fine-tune differing only in seed, so the spread across arms isolates the
# optimization-path component of model uncertainty.
#
# Cost per arm: {n_rows} samples x ~590 MB of SDO NetCDF per epoch = ~{gb_epoch:.0f} GB/epoch,
# re-fetched each epoch because files are deleted after use. At {epochs} epochs that is
# ~{tb_arm:.1f} TB and ~{hours:.1f} h per arm, ~{tb_total:.1f} TB and ~{hours_total:.1f} h total.
{seed0_comment}
set -euo pipefail

cd "$(dirname "${{BASH_SOURCE[0]}}")"

# The allocator fragments on long runs at 4096x4096; expandable segments lets it reuse that
# memory, as run_g4dn_test.sh does.
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True

{runs}
echo "Seed ablation complete: {n_run} arms."
"""

RUN_LINE = """\
echo "=== arm {n}/{n_run}: seed {seed} -- {config} ==="
torchrun --nnodes=1 --nproc_per_node=1 --standalone finetune.py \\
    --gpu --wandb --config_path ./{config}
"""

# Measured from the ten 672hr_stable runs: 3.53-3.97 h each on an L40S at 672 steps/epoch.
HOURS_PER_EPOCH = 3.7 / 6
GB_PER_SAMPLE = 0.590


def main() -> None:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument(
        "--base-config",
        default="./configs_bootstrap/672hr_stable/config_boot01.yaml",
        help="Config every arm is derived from. Its replicate is the one held fixed.",
    )
    p.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    # Named 672hr_stable_seed, after the parent regime whose recipe and replicate these
    # arms reseed, so that run_bootstrap_inference.regime_defaults() resolves all three
    # roots by convention instead of needing explicit --*_root flags.
    p.add_argument("--out-dir", default="./configs_bootstrap/672hr_stable_seed")
    p.add_argument("--runner", default="./run_seed_ablation.sh")
    p.add_argument(
        "--experiment-root",
        default="/mnt/efs/bathomas/ar_seg_bootstrap/672hr_stable_seed",
        help=(
            "Where arm checkpoints land. Sits INSIDE ar_seg_bootstrap/ beside the "
            "672hr_stable members so the regime naming convention resolves it."
        ),
    )
    p.add_argument("--job-id-prefix", default="AR-seg_672hr_stable_seed")
    p.add_argument(
        "--include-seed-0",
        action="store_true",
        help="Have the runner train seed 0 as well, instead of reusing the base config's run.",
    )
    args = p.parse_args()

    base = yaml.safe_load(open(args.base_config, "r"))
    os.makedirs(args.out_dir, exist_ok=True)

    train_index = base["data"]["ar_index_train"][0]
    n_rows = sum(1 for _ in open(train_index)) - 1
    epochs = base["optimizer"]["max_epochs"]
    base_experiment = base["path_experiment"]
    ensemble = os.path.basename(os.path.dirname(args.base_config))

    run_lines, written = [], []
    to_run = [s for s in args.seeds if s != 0 or args.include_seed_0]

    for i, seed in enumerate(args.seeds, start=1):
        config = copy.deepcopy(base)
        experiment = os.path.join(args.experiment_root, f"seed{seed:02d}")

        # Inserted rather than appended so `seed` sits beside job_id at the top of the file,
        # where a reader looking for what distinguishes this arm will actually see it.
        rebuilt = {}
        for key, value in config.items():
            rebuilt[key] = value
            if key == "job_id":
                rebuilt["seed"] = seed
        rebuilt["job_id"] = f"{args.job_id_prefix}_seed{seed:02d}"
        rebuilt["path_experiment"] = experiment
        config = rebuilt

        header = HEADER.format(
            n=i, total=len(args.seeds), seed=seed, train=f"{train_index}  ({n_rows} samples)",
            experiment=experiment, base=args.base_config, ensemble=ensemble,
        )
        if seed == 0:
            header += SEED_0_NOTE.format(base_experiment=base_experiment)

        path = os.path.join(args.out_dir, f"config_seed{seed:02d}.yaml")
        with open(path, "w") as fh:
            fh.write(header)
            yaml.safe_dump(config, fh, sort_keys=False, default_flow_style=False)
        written.append((seed, path, experiment))

        if seed in to_run:
            run_lines.append(
                RUN_LINE.format(
                    n=to_run.index(seed) + 1, n_run=len(to_run), seed=seed,
                    config=os.path.relpath(path, "."),
                )
            )

    gb_epoch = n_rows * GB_PER_SAMPLE
    tb_arm = gb_epoch * epochs / 1000
    hours = HOURS_PER_EPOCH * epochs
    seed0_comment = ""
    if 0 in args.seeds and not args.include_seed_0:
        seed0_comment = (
            f"#\n# Seed 0 is NOT run here: it reproduces the base config bit for bit, so it is"
            f"\n# already trained as {base_experiment}.\n"
            f"# Regenerate with --include-seed-0 to train it anyway.\n"
        )

    runner = RUNNER.format(
        train=train_index, n_run=len(to_run), n_rows=n_rows, gb_epoch=gb_epoch, epochs=epochs,
        tb_arm=tb_arm, hours=hours, tb_total=tb_arm * len(to_run),
        hours_total=hours * len(to_run), seed0_comment=seed0_comment,
        runs="\n".join(run_lines),
    )
    with open(args.runner, "w") as fh:
        fh.write(runner)
    os.chmod(args.runner, os.stat(args.runner).st_mode | stat.S_IXUSR | stat.S_IXGRP)

    print(f"base config : {args.base_config}")
    print(f"replicate   : {train_index}  ({n_rows} samples, {epochs} epochs)")
    for seed, path, experiment in written:
        tag = " (already trained as the base config's run; runner skips it)" if (
            seed == 0 and not args.include_seed_0
        ) else ""
        print(f"  seed {seed:2d} -> {path}\n            {experiment}{tag}")
    print(f"runner      : {args.runner}  ({len(to_run)} arms, ~{hours * len(to_run):.1f} h)")


if __name__ == "__main__":
    main()
